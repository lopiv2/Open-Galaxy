[System.Serializable]
public class PlanetPOIEntry
{
    // Stable identifier used by settlements/roads to reference this POI.
    // Legacy entries without an id fall back to their name.
    public string id;
    public string name;
    public float x;
    public float z;
    public float radius;
}

[System.Serializable]
public class PlanetPOIProp
{
    // Optional stable identifier for tooling/debugging.
    public string id;
    // Catalog type in PropsTypes.json (preferred over the legacy prefab).
    public string type;
    // Legacy field kept so old PlanetPOIs.json entries keep working.
    public string prefab;
    // Optional settlement this fixed prop belongs to visually. The prop is
    // still placed exactly at x/z; it is not generated by the settlement.
    public string site;
    public float x;
    public float z;
    public float rotY;
    // Art-direction multiplier on top of the PropsTypes targetLength.
    public float scale = 1f;
    // Legacy swarm: count instances scattered in a disc of radius (meters)
    // around (x, z). New content should use PlanetPOISite instead.
    public int count = 1;
    public float radius = 0f;
    public int seed = 1;
    public bool randomYaw = false;
    public float scaleVar = 0f;
    public float minDist = 30f;
}

// One type within a settlement. Count is the exact number of instances;
// weight only biases which positions in the layout receive that type.
[System.Serializable]
public class PlanetPOISiteRule
{
    // Catalog type in PropsTypes.json.
    public string type;
    public int count = 1;
    public float weight = 1f;
    public float scale = 1f;
    public float scaleVar = 0f;
    public bool randomYaw = true;
    // Free-form hint for future rules (parked, street, interior...).
    public string mode;
}

// A town/outpost: a group of rules laid out together (grid, radial,
// scatter or alongPath) around one anchor. Linking it to a POI keeps roads
// and navigation targets aligned with the settlement.
[System.Serializable]
public class PlanetPOISite
{
    public string id;
    public string name;
    // PlanetPOIEntry id (or legacy name) this settlement belongs to.
    public string poi;
    public string kind = "town";
    public string layout = "scatter";
    public float x;
    public float z;
    public float radius = 300f;
    // Y rotation of the whole layout, in degrees.
    public float rotation;
    public int seed = 1;
    // Spacing between buildings/cells in meters.
    public float spacing = 45f;
    public PlanetPOISiteRule[] rules;
}

[System.Serializable]
public class PlanetPOICreature
{
    // Resources prefab name inside objects/creatures/ (e.g. "Bantha").
    public string prefab;
    // Herd centre, planet-local meters (same frame as POI/prop x/z).
    public float x;
    public float z;
    // Optional settlement this herd belongs to.
    public string site;
    // Random herd size, inclusive.
    public int herdMin = 3;
    public int herdMax = 6;
    // Initial spread around the herd centre (meters).
    public float herdRadius = 14f;
    // Roaming radius around the herd centre (meters).
    public float wanderRadius = 90f;
    // Walk speed (meters per second).
    public float speed = 2.2f;
    public int seed = 1;
}

[System.Serializable]
public class PlanetPOILocation
{
    public string planet;
    // Entry gate: deterministic spawn XZ in planet-local meters. All POIs
    // are offsets in this same frame (scene-local XZ while on planet).
    public float entryX;
    public float entryZ;
    public PlanetPOIEntry[] pois;
    // Isolated props/landmarks. A prop with count > 1 is the legacy swarm
    // format and still works; new towns should use sites instead.
    public PlanetPOIProp[] props;
    // Towns/outposts made from catalog types.
    public PlanetPOISite[] sites;
    // Ambient fauna herds (not POIs/navigation targets).
    public PlanetPOICreature[] creatures;
}

[System.Serializable]
public class PlanetPOIs
{
    public PlanetPOILocation[] planetPOIsData;
}
